import type { Env } from '../env'
import { apiError, jsonResponse } from '../http/json'
import { consumeMutationLimit } from '../security/mutation-rate-limit'
import { readSession, type SessionData } from '../security/session'
import { announcementStore, validateAnnouncements } from './content'
import { avatarForPlayer } from './avatar'
import { locateIp } from './security'

const STAFF_GROUPS = new Set(['owner', 'admin', 'mod'])
const CONSOLE_GROUPS = new Set(['owner', 'admin'])
const SERVER_ID = /^[a-z0-9][a-z0-9_-]{1,63}$/
const PLAYER = /^(?:[A-Za-z0-9_]{3,16}|[0-9a-fA-F-]{36})$/
const PLAYER_UUID = /^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[1-5][0-9a-fA-F]{3}-[89abAB][0-9a-fA-F]{3}-[0-9a-fA-F]{12}$/
// Promotions are generated by the plugin's UuidV7, independently of player UUIDs.
const PROMOTION_UUID = /^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[1-57][0-9a-fA-F]{3}-[89abAB][0-9a-fA-F]{3}-[0-9a-fA-F]{12}$/
const PLAYER_NAME = /^[A-Za-z0-9_.-]{1,32}$/

interface AdminIdentity {
  session: SessionData
  group: string
}

interface PunishmentInput extends Record<string, string> {
  action: string
  player: string
  reason: string
}

interface MembershipMutationInput extends Record<string, unknown> {
  action: string
  playerUuid: string
  tierKey: string
  days: number
  expiresAt: null
  actor: string
  reason: string
}

export async function adminRoute(request: Request, env: Env, url: URL): Promise<Response> {
  const admin = await requireAdmin(request, env)
  if (admin instanceof Response) return admin

  if (request.method === 'GET' && url.pathname === '/api/admin/session') {
    return jsonResponse({
      ok: true,
      data: {
        playerUuid: admin.session.playerUuid,
        displayName: admin.session.displayName,
        group: admin.group,
        canUseConsole: CONSOLE_GROUPS.has(admin.group),
      },
    })
  }
  if (url.pathname === '/api/admin/announcements') {
    if (request.method === 'GET') return announcementStore(env).fetch('https://content.internal/')
    if (request.method === 'POST') return mutate(request, env, admin, 'announcements', 20, async input => {
      const valid = validateAnnouncements(input)
      if (valid === undefined) return invalidRequest()
      const response = await announcementStore(env).fetch('https://content.internal/', {
        method: 'PUT', body: JSON.stringify({ items: valid }),
      })
      await auditResult(env, admin, response, 'ANNOUNCEMENTS_SAVE', 'website', { count: valid.length })
      return response
    })
  }
  if (url.pathname === '/api/admin/chat-filter/document') {
    const server = url.searchParams.get('server') ?? env.MEMBERSHIP_SERVER_ID
    if (!SERVER_ID.test(server)) return invalidRequest()
    if (request.method === 'GET') return adminRead(env, admin, server, 'admin.chat-filter.document', {})
    if (request.method === 'POST') {
      if (!CONSOLE_GROUPS.has(admin.group)) return apiError(403, 'ADMIN_FORBIDDEN', 'Editing rules requires owner or admin')
      return mutate(request, env, admin, 'chat-filter-save', 10, async input => {
        if (!isRecord(input) || typeof input.content !== 'string' || input.content.length > 512000
          || typeof input.revision !== 'string' || !/^[a-f0-9]{64}$/.test(input.revision)) return invalidRequest()
        try { if (!isRecord(JSON.parse(input.content))) return invalidRequest() } catch { return invalidRequest() }
        const response = await adminRpc(env, admin, 'admin.mutate', 'admin.chat-filter.save', server,
          { content: input.content, revision: input.revision })
        await auditResult(env, admin, response, 'CHAT_FILTER_SAVE', server, { revision: input.revision })
        return passthrough(response)
      })
    }
  }
  if (url.pathname === '/api/admin/discount-codes') {
    if (request.method === 'GET') return adminRead(env, admin, env.MEMBERSHIP_SERVER_ID, 'admin.discount-codes.list', {})
    if (request.method === 'POST') return mutate(request, env, admin, 'discount-code', 20, async input => {
      if (!isRecord(input) || !['CREATE','UPDATE','DELETE'].includes(String(input.action))) return invalidRequest()
      if (input.action !== 'CREATE' && (typeof input.promotionId !== 'string' || !PROMOTION_UUID.test(input.promotionId))) return invalidRequest()
      let payload: Record<string, unknown> = { action: input.action, promotionId: input.promotionId }
      if (input.action !== 'DELETE') {
        if (typeof input.discountCode !== 'string' || !/^[\p{L}\p{N}_-]{1,32}$/u.test(input.discountCode.normalize('NFC'))
          || typeof input.name !== 'string' || !input.name.trim() || input.name.length > 64
          || !Number.isSafeInteger(input.percentOffBps) || (input.percentOffBps as number) < 1 || (input.percentOffBps as number) > 10000
          || !(input.targetTierKey === null || typeof input.targetTierKey === 'string' && SERVER_ID.test(input.targetTierKey))
          || typeof input.startsAt !== 'string' || !Number.isFinite(Date.parse(input.startsAt))
          || !(input.endsAt === null || typeof input.endsAt === 'string' && Number.isFinite(Date.parse(input.endsAt)) && Date.parse(input.endsAt) > Date.parse(input.startsAt))) return invalidRequest()
        if (!(input.maxUsesPerPlayer === undefined || input.maxUsesPerPlayer === null || input.maxUsesPerPlayer === 1)
          || !(input.maxPlayers === undefined || input.maxPlayers === null || Number.isSafeInteger(input.maxPlayers) && (input.maxPlayers as number) >= 1 && (input.maxPlayers as number) <= 1000000)) return invalidRequest()
        payload = { ...payload, name: input.name.trim(), discountCode: input.discountCode.normalize('NFC').toUpperCase(), targetTierKey: input.targetTierKey,
          percentOffBps: input.percentOffBps, startsAt: input.startsAt, endsAt: input.endsAt, maxUsesPerPlayer: input.maxUsesPerPlayer ?? null, maxPlayers: input.maxPlayers ?? null }
      }
      const response = await adminRpc(env, admin, 'admin.mutate', 'admin.discount-codes.mutate', env.MEMBERSHIP_SERVER_ID, payload)
      await auditResult(env, admin, response, `DISCOUNT_CODE_${input.action}`, 'memberships', { ...payload })
      return passthrough(response)
    })
  }
  if (request.method === 'GET' && url.pathname === '/api/admin/promotions') {
    return adminRead(env, admin, env.MEMBERSHIP_SERVER_ID, 'admin.promotions.list', {})
  }
  if (request.method === 'POST' && url.pathname === '/api/admin/promotions') {
    return mutate(request, env, admin, 'promotion', 20, async input => {
      if (!isRecord(input)) return invalidRequest()
      let payload: Record<string, unknown>
      if (input.action === 'STOP' && typeof input.promotionId === 'string' && PROMOTION_UUID.test(input.promotionId)) {
        payload = { action: 'STOP', promotionId: input.promotionId }
      } else if (input.action === 'CREATE' && typeof input.name === 'string' && input.name.trim().length > 0
        && input.name.length <= 64 && Number.isSafeInteger(input.percentOffBps)
        && (input.percentOffBps as number) >= 1 && (input.percentOffBps as number) <= 10000
        && (input.targetTierKey === null || (typeof input.targetTierKey === 'string' && SERVER_ID.test(input.targetTierKey)))
        && typeof input.startsAt === 'string' && typeof input.endsAt === 'string'
        && Number.isFinite(Date.parse(input.startsAt)) && Number.isFinite(Date.parse(input.endsAt))
        && Date.parse(input.endsAt) > Math.max(Date.now(), Date.parse(input.startsAt))) {
        payload = { action: 'CREATE', name: input.name.trim(), percentOffBps: input.percentOffBps,
          targetTierKey: input.targetTierKey, startsAt: new Date(input.startsAt).toISOString(), endsAt: new Date(input.endsAt).toISOString() }
      } else return invalidRequest()
      const response = await adminRpc(env, admin, 'admin.mutate', 'admin.promotions.mutate', env.MEMBERSHIP_SERVER_ID, payload)
      await auditResult(env, admin, response, `PROMOTION_${payload.action}`, 'memberships', payload)
      return passthrough(response)
    })
  }
  if (request.method === 'GET' && url.pathname === '/api/admin/points/batches') {
    return adminRead(env, admin, env.POINTS_SERVER_ID, 'admin.points.batches', {})
  }
  if (request.method === 'POST' && url.pathname === '/api/admin/points/batches') {
    if (!CONSOLE_GROUPS.has(admin.group)) return apiError(403, 'ADMIN_FORBIDDEN', 'Bulk points require owner or admin')
    return mutate(request, env, admin, 'bulk-points', 5, async input => {
      if (!isRecord(input) || typeof input.batchId !== 'string' || !PLAYER_UUID.test(input.batchId)
        || !Number.isSafeInteger(input.points) || (input.points as number) < 1 || (input.points as number) > 10000000
        || !['ALL', 'BOUND'].includes(String(input.scope)) || typeof input.reason !== 'string'
        || !input.reason.trim() || input.reason.length > 255) return invalidRequest()
      const payload = { batchId: input.batchId, points: input.points, scope: input.scope, reason: input.reason.trim() }
      const response = await adminRpc(env, admin, 'admin.mutate', 'admin.points.grant', env.POINTS_SERVER_ID, payload, 12000)
      await auditResult(env, admin, response, 'POINTS_BULK_GRANT', input.batchId, payload)
      return passthrough(response)
    })
  }
  if (request.method === 'GET' && url.pathname === '/api/admin/servers') {
    return adminServers(env, admin)
  }
  if (request.method === 'GET' && url.pathname === '/api/admin/players') {
    const scope = pageString(url, 'scope', 16, 'registered')
    if (scope !== 'registered' && scope !== 'online') return invalidRequest()
    return adminRead(
      env,
      admin,
      scope === 'online' ? env.PROFILE_SERVER_ID : env.AUTH_SERVER_ID,
      scope === 'online' ? 'admin.players.online' : 'admin.players.registered',
      {
        page: pageNumber(url, 'page', 1, 100_000, 1),
        pageSize: pageNumber(url, 'pageSize', 1, 100, 10),
        query: pageString(url, 'query', 36, ''),
      },
    ).then(response => scope === 'registered' ? enrichPlayerLocations(response, request) : response)
  }
  if (request.method === 'GET' && url.pathname === '/api/admin/players/detail') {
    const playerUuid = url.searchParams.get('uuid') ?? ''
    const playerName = url.searchParams.get('name') ?? ''
    if (!PLAYER_UUID.test(playerUuid) || !PLAYER_NAME.test(playerName)) return invalidRequest()
    const [detailsResponse, profileResponse] = await Promise.all([
      adminRead(env, admin, env.AUTH_SERVER_ID, 'admin.players.detail', { playerUuid, playerName }),
      minecraftRpc(env, { capability: 'profile.read', operation: 'profile.read', serverId: env.PROFILE_SERVER_ID,
        payload: { playerUuid }, timeoutMs: 5_000 }),
    ])
    const details = await readEnvelope(detailsResponse)
    if (!detailsResponse.ok || !isRecord(details.data)) return jsonResponse(details, { status: detailsResponse.status })
    const live = await readEnvelope(profileResponse)
    if (!profileResponse.ok || !isRecord(live.data) || typeof live.data.online !== 'boolean') {
      return apiError(503, 'PLAYER_PROFILE_UNAVAILABLE', 'Player online status is temporarily unavailable', true)
    }
    details.data.online = live.data.online
    details.data.serverId = typeof live.data.serverId === 'string' ? live.data.serverId : null
    if (live.data.online && typeof live.data.connectionIp === 'string') details.data.lastLoginIp = live.data.connectionIp
    details.data.lastLoginLocation = typeof details.data.lastLoginIp === 'string'
      ? await locateIp(details.data.lastLoginIp, request) : null
    return jsonResponse(details)
  }
  if (request.method === 'GET' && url.pathname === '/api/admin/players/avatar') {
    const playerUuid = url.searchParams.get('uuid') ?? ''
    const playerName = url.searchParams.get('name') ?? ''
    if (!PLAYER_UUID.test(playerUuid) || !PLAYER_NAME.test(playerName)) return invalidRequest()
    return avatarForPlayer(request, env, playerUuid, playerName)
  }
  if (request.method === 'POST' && url.pathname === '/api/admin/players/membership') {
    return mutate(request, env, admin, 'player-membership', 30, async input => {
      const valid = membershipMutation(input, admin)
      if (valid === undefined) return invalidRequest()
      const protectedResponse = await rejectStaffTarget(env, valid.playerUuid)
      if (protectedResponse !== undefined) return protectedResponse
      const response = await adminRpc(
        env,
        admin,
        'admin.mutate',
        'admin.players.membership',
        env.MEMBERSHIP_SERVER_ID,
        valid,
        12_000,
      )
      await auditResult(env, admin, response, `PLAYER_MEMBERSHIP_${valid.action}`,
        valid.playerUuid, valid)
      return passthrough(response)
    })
  }
  if (request.method === 'GET' && url.pathname === '/api/admin/redeem') {
    return adminRead(env, admin, env.REDEEM_SERVER_ID, 'admin.redeem.list', {
      section: pageString(url, 'section', 16, 'batches'),
      page: pageNumber(url, 'page', 1, 100_000, 1),
      pageSize: pageNumber(url, 'pageSize', 1, 100, 20),
    })
  }
  if (request.method === 'POST' && url.pathname === '/api/admin/redeem/generate') {
    return mutate(request, env, admin, 'redeem-generate', 10, async input => {
      const valid = redeemGeneration(input)
      if (valid === undefined) return invalidRequest()
      const response = await adminRpc(env, admin, 'admin.mutate', 'admin.redeem.generate',
        env.REDEEM_SERVER_ID, valid, 12_000)
      await auditResult(env, admin, response, 'REDEEM_GENERATE', 'redeem-batch', valid)
      return passthrough(response)
    })
  }
  if (request.method === 'GET' && url.pathname === '/api/admin/reports') {
    return adminRead(env, admin, env.MEMBERSHIP_SERVER_ID, 'admin.reports.list', {
      status: pageString(url, 'status', 24, 'ALL').toUpperCase(),
      query: pageString(url, 'query', 80, ''),
      page: pageNumber(url, 'page', 1, 100_000, 1),
      pageSize: pageNumber(url, 'pageSize', 1, 100, 5),
    })
  }
  if (request.method === 'POST' && url.pathname === '/api/admin/reports/status') {
    return mutate(request, env, admin, 'report-status', 30, async input => {
      if (!isRecord(input) || !Number.isSafeInteger(input.reportId)
        || (input.reportId as number) < 1 || typeof input.status !== 'string'
        || !new Set(['OPEN', 'IN_PROGRESS', 'CLOSED', 'FALSE']).has(input.status.toUpperCase())) {
        return invalidRequest()
      }
      const payload = { reportId: input.reportId, status: input.status.toUpperCase() }
      const response = await adminRpc(env, admin, 'admin.mutate', 'admin.reports.update',
        env.MEMBERSHIP_SERVER_ID, payload)
      await auditResult(env, admin, response, 'REPORT_STATUS', String(input.reportId), payload)
      return passthrough(response)
    })
  }
  if (request.method === 'GET' && url.pathname === '/api/admin/chat-filter') {
    const query = url.searchParams.get('query')?.trim() ?? ''
    const server = url.searchParams.get('server')?.trim() ?? ''
    const word = url.searchParams.get('word')?.trim() ?? ''
    const from = url.searchParams.get('from') ?? ''
    const to = url.searchParams.get('to') ?? ''
    if (query.length > 200 || word.length > 200 || server.length > 64
      || (server && !SERVER_ID.test(server))
      || [from, to].some(value => value && (value.length > 40 || !Number.isFinite(Date.parse(value))))
      || (from && to && Date.parse(from) > Date.parse(to))) return invalidRequest()
    return adminRead(env, admin, env.MEMBERSHIP_SERVER_ID, 'admin.chat-filter.list', {
      page: pageNumber(url, 'page', 1, 100_000, 1),
      pageSize: pageNumber(url, 'pageSize', 1, 100, 10),
      query, server, word, from, to,
    })
  }
  if (request.method === 'GET' && url.pathname === '/api/admin/redstone') {
    return adminRead(env, admin, env.MEMBERSHIP_SERVER_ID, 'admin.redstone.list', {
      page: pageNumber(url, 'page', 1, 100_000, 1),
      pageSize: pageNumber(url, 'pageSize', 1, 100, 20),
    })
  }
  if (request.method === 'GET' && url.pathname === '/api/admin/punishments') {
    return adminPunishmentRead(
      env,
      admin,
      pageNumber(url, 'page', 1, 100_000, 1),
      pageNumber(url, 'pageSize', 1, 100, 10),
    )
  }
  if (request.method === 'POST' && url.pathname === '/api/admin/punishments') {
    return mutate(request, env, admin, 'punishment', 20, async input => {
      const valid = punishment(input)
      if (valid === undefined) return invalidRequest()
      const response = await adminRpc(env, admin, 'admin.mutate', 'admin.punishments.execute',
        env.PROFILE_SERVER_ID, valid)
      await auditResult(env, admin, response, `PUNISHMENT_${valid.action}`, valid.player, valid)
      return passthrough(response)
    })
  }

  const serverMatch = /^\/api\/admin\/servers\/([a-z0-9][a-z0-9_-]{1,63})\/(logs|command)$/.exec(
    url.pathname,
  )
  if (serverMatch !== null && request.method === 'GET' && serverMatch[2] === 'logs') {
    return adminRead(env, admin, serverMatch[1]!, 'admin.server.logs', {
      lines: pageNumber(url, 'lines', 20, 500, 200),
    })
  }
  if (serverMatch !== null && request.method === 'POST' && serverMatch[2] === 'command') {
    if (!CONSOLE_GROUPS.has(admin.group)) {
      return apiError(403, 'ADMIN_CONSOLE_FORBIDDEN', 'Console access is forbidden')
    }
    return mutate(request, env, admin, 'server-command', 20, async input => {
      if (!isRecord(input) || typeof input.command !== 'string'
        || input.command.trim().length < 1 || input.command.length > 512
        || /[\r\n]/.test(input.command)) {
        return invalidRequest()
      }
      const payload = { command: input.command.trim() }
      const response = await adminRpc(env, admin, 'admin.mutate', 'admin.server.command',
        serverMatch[1]!, payload)
      await auditResult(env, admin, response, 'SERVER_COMMAND', serverMatch[1]!, payload)
      return passthrough(response)
    })
  }
  return apiError(404, 'NOT_FOUND', 'Not found')
}

async function adminPunishmentRead(
  env: Env,
  admin: AdminIdentity,
  page: number,
  pageSize: number,
): Promise<Response> {
  const combined = await adminRpc(env, admin, 'admin.read', 'admin.punishments.list',
    env.PROFILE_SERVER_ID, { type: 'all', page, pageSize })
  if (combined.ok || combined.status !== 400) return passthrough(combined)

  // Compatibility for a running Velocity node that has not loaded the new CCTSystem jar yet.
  const fetchSize = Math.min(page * pageSize, 100)
  const [bans, kicks] = await Promise.all([
    adminRpc(env, admin, 'admin.read', 'admin.punishments.list', env.PROFILE_SERVER_ID,
      { type: 'bans', page: 1, pageSize: fetchSize }),
    adminRpc(env, admin, 'admin.read', 'admin.punishments.list', env.PROFILE_SERVER_ID,
      { type: 'kicks', page: 1, pageSize: fetchSize }),
  ])
  const [banEnvelope, kickEnvelope] = await Promise.all([readEnvelope(bans), readEnvelope(kicks)])
  if (!bans.ok || !kicks.ok || !isPageEnvelope(banEnvelope) || !isPageEnvelope(kickEnvelope)) {
    return passthrough(combined)
  }
  const allItems = [...banEnvelope.data.items, ...kickEnvelope.data.items]
    .filter(isRecord)
    .sort((left, right) => numeric(right.dateStart) - numeric(left.dateStart))
  const totalItems = numeric(banEnvelope.data.totalItems) + numeric(kickEnvelope.data.totalItems)
  const offset = (page - 1) * pageSize
  return jsonResponse({
    ok: true,
    data: {
      items: allItems.slice(offset, offset + pageSize),
      page,
      pageSize,
      totalItems,
      totalPages: Math.max(1, Math.ceil(totalItems / pageSize)),
    },
  })
}

function isPageEnvelope(value: Record<string, unknown>): value is Record<string, unknown> & {
  data: { items: unknown[], totalItems: unknown }
} {
  return isRecord(value.data) && Array.isArray(value.data.items)
}

function numeric(value: unknown): number {
  return typeof value === 'number' && Number.isFinite(value) ? value : 0
}

async function requireAdmin(request: Request, env: Env): Promise<AdminIdentity | Response> {
  const session = await readSession(request, env)
  if (session === undefined) return apiError(401, 'SESSION_INVALID', 'Session is invalid')
  let envelope: Record<string, unknown> = {}
  let authorized = false
  for (let attempt = 0; attempt < 3; attempt += 1) {
    const response = await minecraftRpc(env, {
      capability: 'profile.read',
      operation: 'profile.read',
      serverId: env.PROFILE_SERVER_ID,
      payload: { playerUuid: session.playerUuid },
      timeoutMs: 5_000,
    })
    envelope = await readEnvelope(response)
    if (response.ok && isRecord(envelope.data)
      && typeof envelope.data.primaryGroup === 'string') {
      authorized = true
      break
    }
    if (attempt < 2) await delay(250 * (attempt + 1))
  }
  if (!authorized || !isRecord(envelope.data)
    || typeof envelope.data.primaryGroup !== 'string') {
    return apiError(503, 'ADMIN_AUTH_UNAVAILABLE', 'Admin authorization is unavailable', true)
  }
  const group = envelope.data.primaryGroup.trim().toLowerCase()
  if (!STAFF_GROUPS.has(group)) {
    return apiError(403, 'ADMIN_FORBIDDEN', 'Admin access is forbidden')
  }
  return { session, group }
}

async function enrichPlayerLocations(response: Response, request: Request): Promise<Response> {
  const envelope = await readEnvelope(response)
  if (!response.ok || !isRecord(envelope.data) || !Array.isArray(envelope.data.items)) {
    return jsonResponse(envelope, { status: response.status })
  }
  const items = envelope.data.items
  await Promise.all(items.map(async value => {
    if (!isRecord(value) || typeof value.lastLoginIp !== 'string') return
    value.lastLoginLocation = await locateIp(value.lastLoginIp, request)
  }))
  return jsonResponse(envelope, { status: response.status })
}

function delay(ms: number): Promise<void> {
  return new Promise(resolve => setTimeout(resolve, ms))
}

async function adminRead(
  env: Env,
  admin: AdminIdentity,
  serverId: string,
  operation: string,
  payload: Record<string, unknown>,
): Promise<Response> {
  return passthrough(await adminRpc(env, admin, 'admin.read', operation, serverId, payload))
}

async function adminRpc(
  env: Env,
  admin: AdminIdentity,
  capability: 'admin.read' | 'admin.mutate',
  operation: string,
  serverId: string,
  payload: Record<string, unknown>,
  timeoutMs = 8_000,
): Promise<Response> {
  if (!SERVER_ID.test(serverId)) return apiError(400, 'ADMIN_SERVER_INVALID', 'Invalid server')
  return minecraftRpc(env, {
    capability,
    operation,
    serverId,
    payload: {
      ...payload,
      actorUuid: admin.session.playerUuid,
      actorName: admin.session.displayName,
      actorGroup: admin.group,
    },
    timeoutMs,
  })
}

async function adminServers(env: Env, admin: AdminIdentity): Promise<Response> {
  const bridge = env.BRIDGE_COORDINATOR.getByName(env.CCT_NETWORK_ID)
  const response = await bridge.fetch('https://bridge.internal/status')
  const envelope = await readEnvelope(response)
  if (!response.ok || !isRecord(envelope.data) || !Array.isArray(envelope.data.nodes)) {
    return apiError(503, 'ADMIN_SERVERS_UNAVAILABLE', 'Server list is unavailable', true)
  }
  const seen = new Set<string>()
  const candidates = envelope.data.nodes.filter(isRecord).sort((a, b) =>
    Number(b.ready === true) - Number(a.ready === true)
    || String(b.lastSeenAt ?? '').localeCompare(String(a.lastSeenAt ?? '')),
  )
  const nodes = candidates.flatMap(value => {
    if (!isRecord(value) || typeof value.serverId !== 'string'
      || typeof value.nodeId !== 'string' || typeof value.platform !== 'string'
      || typeof value.ready !== 'boolean' || !Array.isArray(value.capabilities)) return []
    if (!value.capabilities.includes('admin.read') || seen.has(value.serverId)) return []
    seen.add(value.serverId)
    return [{
      serverId: value.serverId,
      nodeId: value.nodeId,
      platform: value.platform,
      ready: value.ready,
      canUseConsole: CONSOLE_GROUPS.has(admin.group) && value.capabilities.includes('admin.mutate'),
    }]
  })
  return jsonResponse({ ok: true, data: { nodes } })
}

async function mutate(
  request: Request,
  env: Env,
  admin: AdminIdentity,
  action: string,
  limit: number,
  operation: (input: unknown) => Promise<Response>,
): Promise<Response> {
  if (request.headers.get('x-cct-csrf') !== '1') {
    return apiError(403, 'CSRF_REQUIRED', 'CSRF header is required')
  }
  const limited = await consumeMutationLimit(request, env, admin.session.playerUuid, action, limit)
  if (limited !== undefined) return limited
  const input = await readBody(request)
  if (input === undefined) return invalidRequest()
  return operation(input)
}

